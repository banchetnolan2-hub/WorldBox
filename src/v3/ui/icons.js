export function icon(name, cls = '') {
  const svg = ICONS[name];
  if (!svg) return '';
  return svg.replace(/<!--[\s\S]*?-->/g, '').trim()
    .replace('class="lucide', `aria-hidden="true" class="ic ${cls} lucide`)
    .replace(/\s(width|height)="24"/g, '')
    .replace('stroke-width="2"', 'stroke-width="1.75"');
}

// remplace les <i data-icon="…"> du document
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    const html = icon(el.dataset.icon, el.className);
    if (!html) return;
    const tpl = document.createElement('template');
    tpl.innerHTML = html.trim();
    el.replaceWith(tpl.content.firstChild);
  });
}
